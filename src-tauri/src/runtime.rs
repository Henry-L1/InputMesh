#[derive(Debug, Clone, Copy)]
struct NativeScreenBounds {
    x: i32,
    y: i32,
    width: u32,
    height: u32,
}

impl NativeScreenBounds {
    fn contains(&self, x: f64, y: f64) -> bool {
        x >= f64::from(self.x)
            && x < f64::from(self.x) + f64::from(self.width)
            && y >= f64::from(self.y)
            && y < f64::from(self.y) + f64::from(self.height)
    }
}

#[derive(Debug, Clone)]
struct PairSession {
    connection_id: Uuid,
    /// Request identifier generated by this endpoint. A valid remote approval
    /// must echo this value, so approvals cannot be reused across connections.
    request_id: String,
    /// Request identifier generated by the peer. Our approval echoes this ID.
    remote_request_id: Option<String>,
    remote_static_key: [u8; 32],
    local_approved: bool,
    remote_approved: bool,
}

#[derive(Debug)]
struct EdgeAttempt {
    from_screen_id: String,
    to_screen_id: String,
    direction: Direction,
    started_at: Instant,
    travel_px: f64,
}

#[derive(Debug)]
struct ControlState {
    generation: u64,
    holder: DeviceId,
    lease_id: String,
    input_set_id: String,
    sequence: u64,
    pointer: Option<PointerPosition>,
    last_native_pointer: Option<(f64, f64)>,
    pressed_hid: HashSet<u16>,
    claim_announced: bool,
    last_remote_sequence: u64,
    edge_attempt: Option<EdgeAttempt>,
    pointer_parking: Option<(f64, f64)>,
    remote_pressed_keys: HashSet<String>,
    remote_pressed_buttons: HashSet<String>,
}

impl ControlState {
    fn new(local_id: DeviceId, primary_screen: Option<&ScreenInfo>) -> Self {
        let generation = unix_millis();
        Self {
            generation,
            holder: local_id,
            lease_id: format!("{generation:020}:{local_id}"),
            input_set_id: format!("physical:{local_id}"),
            sequence: 0,
            pointer: primary_screen.map(|screen| {
                PointerPosition::new(
                    screen.id.clone(),
                    f64::from(screen.width) / 2.0,
                    f64::from(screen.height) / 2.0,
                )
            }),
            last_native_pointer: None,
            pressed_hid: HashSet::new(),
            claim_announced: false,
            last_remote_sequence: 0,
            edge_attempt: None,
            pointer_parking: None,
            remote_pressed_keys: HashSet::new(),
            remote_pressed_buttons: HashSet::new(),
        }
    }

    fn next_sequence(&mut self) -> u64 {
        self.sequence = self.sequence.saturating_add(1);
        self.sequence
    }
}

