fn edge_transition_ready(
    attempt: &mut Option<EdgeAttempt>,
    transition: &ScreenTransition,
    travel_px: f64,
    settings: &SharingSettings,
) -> bool {
    let now = Instant::now();
    let matches_existing = attempt.as_ref().is_some_and(|current| {
        current.from_screen_id == transition.from_screen_id
            && current.to_screen_id == transition.to_screen_id
            && current.direction == transition.direction
    });
    if !matches_existing {
        *attempt = Some(EdgeAttempt {
            from_screen_id: transition.from_screen_id.clone(),
            to_screen_id: transition.to_screen_id.clone(),
            direction: transition.direction,
            started_at: now,
            travel_px: 0.0,
        });
    }
    let current = attempt.as_mut().expect("edge attempt was just initialized");
    current.travel_px += travel_px.max(0.0);
    let delay_ready =
        current.started_at.elapsed().as_millis() >= u128::from(settings.switch_delay_ms);
    let resistance_ready = current.travel_px >= f64::from(settings.edge_resistance_px);
    if delay_ready && resistance_ready {
        *attempt = None;
        true
    } else {
        false
    }
}

fn local_input_can_reclaim_control(event: &NativeInputEvent, settings: &SharingSettings) -> bool {
    settings.take_control_on_local_input || matches!(event, NativeInputEvent::PointerMoved { .. })
}

/// Native cursors are clamped to the last pixel of a display. Reaching that
/// pixel with a slow 1 px movement would otherwise leave the logical pointer
/// one pixel short of the topology boundary, after which Windows reports only
/// zero coordinate deltas. Add the smallest possible outward overshoot while
/// preserving the device's original movement magnitude.
fn native_edge_overshoot(
    native_position: f64,
    native_origin: i32,
    native_extent: u32,
    delta: f64,
) -> Option<f64> {
    if native_extent == 0 || !native_position.is_finite() || !delta.is_finite() {
        return None;
    }
    let first = f64::from(native_origin);
    let last = first + f64::from(native_extent.saturating_sub(1));
    if native_position >= last && delta > 0.0 {
        Some(delta.max(1.0) + 1.0)
    } else if native_position <= first && delta < 0.0 {
        Some(delta.min(-1.0) - 1.0)
    } else {
        None
    }
}

/// Recovers outward physical motion that Windows reports at an unchanged,
/// display-clamped cursor position. Candidates are limited to native edges
/// whose matching topology edge leads directly to a screen owned by a peer.
fn clamped_remote_edge_delta(
    topology: &ScreenTopology,
    start: &PointerPosition,
    native_bounds: NativeScreenBounds,
    native_x: f64,
    native_y: f64,
    local_id: DeviceId,
) -> Option<(f64, f64)> {
    let first_x = f64::from(native_bounds.x);
    let first_y = f64::from(native_bounds.y);
    let last_x = first_x + f64::from(native_bounds.width.saturating_sub(1));
    let last_y = first_y + f64::from(native_bounds.height.saturating_sub(1));
    let candidates = [
        (native_x <= first_x, (-2.0, 0.0)),
        (native_x >= last_x, (2.0, 0.0)),
        (native_y <= first_y, (0.0, -2.0)),
        (native_y >= last_y, (0.0, 2.0)),
    ];

    candidates.into_iter().find_map(|(at_edge, delta)| {
        if !at_edge {
            return None;
        }
        let moved = topology
            .move_pointer_by(&start.screen_id, start.x, start.y, delta.0, delta.1)
            .ok()?;
        moved
            .transitions
            .iter()
            .any(|transition| {
                topology
                    .screen(&transition.to_screen_id)
                    .is_some_and(|screen| screen.owner_device_id != local_id)
            })
            .then_some(delta)
    })
}

fn drain_remote_releases(control: &mut ControlState) -> Vec<NativeInputEvent> {
    let mut releases = Vec::with_capacity(
        control.remote_pressed_keys.len() + control.remote_pressed_buttons.len(),
    );
    releases.extend(
        control
            .remote_pressed_keys
            .drain()
            .map(|code| NativeInputEvent::Key {
                code,
                pressed: false,
            }),
    );
    releases.extend(control.remote_pressed_buttons.drain().map(|button| {
        NativeInputEvent::PointerButton {
            button,
            pressed: false,
        }
    }));
    releases
}

